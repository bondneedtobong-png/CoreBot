def normalize_phone_digits(phone: str) -> str:
    """Только цифры; ведущие 00 убрать."""
    if not phone:
        return ""
    d = re.sub(r"\D", "", phone)
    if d.startswith("00"):
        d = d[2:]
    return d


def infer_country_from_phone(phone: str) -> str:
    """
    Возвращает условное название региона или «Не определено».
    8XXXXXXXXXX (10 цифр после 8) часто РФ без +7 — подменяем на 7...
    """
    d = normalize_phone_digits(phone)
    if not d:
        return "Не указан"

    # 8 9XX XXX XX XX -> 7 9XX...
    if len(d) == 11 and d.startswith("8"):
        d = "7" + d[1:]

    for prefix, name in _PREFIXES:
        if d.startswith(prefix):
            return name

    if len(d) >= 10:
        return "Прочее / неизвестный код"

    return "Короткий номер"


def aggregate_geo_counts(phones: List[str]) -> List[Tuple[str, int]]:
    """Список (страна, количество), по убыванию count."""
    from collections import Counter

    c: Counter = Counter()
    for p in phones:
        c[infer_country_from_phone(p)] += 1
    return sorted(c.items(), key=lambda x: (-x[1], x[0]))
